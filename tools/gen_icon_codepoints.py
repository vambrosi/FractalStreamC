#!/usr/bin/env python3
"""Generate the Material Icons name -> codepoint table used by ui_icon_lookup().

Usage (from the repository root; both arguments are optional and default to the values below):

  python3 tools/gen_icon_codepoints.py third_party/fonts/MaterialIcons-Regular.codepoints third_party/fonts/material_icons_codepoints.c

Input: Google's `MaterialIcons-Regular.codepoints`, one "name hex_codepoint" pair per line (several names can share
a codepoint: aliases; a repeated name keeps its first codepoint).  Output: a C array sorted by name in strcmp order, ready for binary search.  The codepoints
file must come from the same release as MaterialIcons-Regular.ttf (tests/test_ui.c checks that every codepoint
has a glyph in the embedded font).
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "third_party/fonts/MaterialIcons-Regular.codepoints"
dst = sys.argv[2] if len(sys.argv) > 2 else "third_party/fonts/material_icons_codepoints.c"

entries = {}
for n, line in enumerate(open(src, encoding="ascii"), 1):
    line = line.strip()
    if not line:
        continue
    parts = line.split()
    if len(parts) != 2 or not re.fullmatch(r"[a-z0-9_]+", parts[0]) or not re.fullmatch(r"[0-9a-fA-F]{4,6}", parts[1]):
        sys.exit("%s:%d: cannot parse %r" % (src, n, line))
    name, cp = parts[0], int(parts[1], 16)
    if cp > 0x10FFFF:
        sys.exit("%s:%d: codepoint out of range" % (src, n))
    if name in entries:  # upstream lists the misspelled "flourescent" twice; the first one (= "fluorescent") wins
        print("note: %s:%d: duplicate name %r ignored (keeping 0x%04x)" % (src, n, name, entries[name]), file=sys.stderr)
        continue
    entries[name] = cp

# Python compares ASCII strings by byte value, which is exactly strcmp order.
names = sorted(entries)
with open(dst, "w") as f:
    f.write("/* Generated by tools/gen_icon_codepoints.py -- do not edit.\n")
    f.write(" * Regenerate from the repository root with:\n")
    f.write(" *   python3 tools/gen_icon_codepoints.py %s %s\n" % (src, dst))
    f.write(" * Source: https://github.com/google/material-design-icons, font/MaterialIcons-Regular.codepoints\n")
    f.write(" * (Apache License 2.0, see LICENSE-MaterialIcons.txt).  %d names, sorted by strcmp for binary search. */\n" % len(names))
    f.write("static const struct { const char *name; u32 cp; } material_icon_names[] = {\n")
    for name in names:
        f.write('    { "%s", 0x%04x },\n' % (name, entries[name]))
    f.write("};\n")
