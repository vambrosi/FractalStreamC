#!/usr/bin/env python3
"""Embed binary files as C byte arrays.  Usage: embed.py out.c name=path [name=path ...]

The command line is copied into the header of the generated file, so the file always says how to regenerate it.
Run from the repository root.  For the bundled fonts:

  python3 tools/embed.py third_party/fonts/fonts_embedded.c font_mono_ttf=third_party/fonts/DejaVuSansMono-subset.ttf font_sans_ttf=third_party/fonts/DejaVuSans-subset.ttf font_icons_ttf=third_party/fonts/MaterialIcons-Regular.ttf
"""
import sys

if len(sys.argv) < 3:
    sys.exit(__doc__)
out = sys.argv[1]
with open(out, "w") as f:
    f.write("/* Generated by tools/embed.py -- do not edit.\n")
    f.write(" * Regenerate from the repository root with:\n")
    f.write(" *   python3 tools/embed.py " + " ".join(sys.argv[1:]) + "\n")
    f.write(" */\n")
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        data = open(path, "rb").read()
        f.write("static const unsigned char %s[%d] = {\n" % (name, len(data)))
        for i in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[i:i+24]) + ",\n")
        f.write("};\n")
