#!/bin/sh
# gen_shaders.sh - compile the renderer's fixed GLSL shaders to SPIR-V C arrays.
#
#   src/shaders/*.glsl   -> src/shaders_spv.h        (used by src/gfx.c)
#   tests/shaders/*.glsl -> tests/test_gfx_shaders.h (used by tests/test_gfx.c, tests/gfx_demo.c)
#
# The generated headers are checked in, so glslangValidator (and spirv-val, used
# to double-check the output) are only needed when a shader is edited.
# File names are <name>.<stage>.glsl with stage = vert|frag; the array for
# src/shaders/ui.frag.glsl is called gfx_spv_ui_frag (tests: gfx_test_spv_...).
# Output is SPIR-V 1.0 for Vulkan 1.0 (glslangValidator's default with -V).
set -e
cd "$(dirname "$0")/.."
TMP=${TMPDIR:-/tmp}/fs_gen_shaders.$$
mkdir -p "$TMP"
trap 'rm -rf "$TMP"' EXIT

gen() {   # gen <output header> <array name prefix> <glsl files...>
  out=$1; prefix=$2; shift 2
  {
    guard=FS_$(basename "$out" | tr 'a-z.' 'A-Z_')
    echo "/* $(basename "$out") - generated by tools/gen_shaders.sh from the GLSL sources; do not edit. */"
    echo "#ifndef $guard"
    echo "#define $guard"
    echo "#include <stdint.h>"
    for f in "$@"; do
      base=$(basename "$f" .glsl)            # e.g. ui.frag
      stage=${base##*.}                      # frag
      name=${prefix}$(echo "$base" | tr '.-' '__')
      glslangValidator -V -S "$stage" -o "$TMP/s.spv" "$f" >/dev/null
      spirv-val --target-env vulkan1.0 "$TMP/s.spv"
      glslangValidator -V -S "$stage" --vn "$name" -o "$TMP/s.h" "$f" >/dev/null
      echo
      echo "/* $f */"
      # glslang writes "const uint32_t name[] = {...};" plus a version comment and
      # "#pragma once"; keep only the array and make it static.
      grep -v -e '#pragma once' -e '^[[:space:]]*// [0-9]' "$TMP/s.h" | sed 's/^const uint32_t/static const uint32_t/'
    done
    echo
    echo "#endif"
  } > "$out"
  echo "wrote $out"
}

gen src/shaders_spv.h gfx_spv_ src/shaders/*.glsl
gen tests/test_gfx_shaders.h gfx_test_spv_ tests/shaders/*.glsl
